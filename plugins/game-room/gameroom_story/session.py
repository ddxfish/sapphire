def _as_bool(v, default=True):
    if v is None:
        return default
    if isinstance(v, bool):
        return v
    return str(v).strip().lower() not in ("false", "0", "no", "off", "")


def conduct_for(story):
    """(universal_text | None, dm_guide | None) — the two GM layers."""
    slug = story["meta"]["slug"]
    uni = _store().get("storycfg:universal") or {}
    mine = _store().get(f"storycfg:{slug}") or {}
    universal = None
    if _as_bool(mine.get("use_universal"), True):
        universal = (uni.get("text") or "").strip() or UNIVERSAL_GM_DEFAULT
    dm = (mine.get("dm_guide") or "").strip() \
        or (story["meta"].get("dm_guide") or "").strip() or None
    return universal, dm


def refresh_prompt(system, session=None):
    """Re-render + re-activate the chat's story prompt — the live tuning
    loop: saving GM settings lands on the very next turn."""
    chat = _chat_name(system, session)
    story, state = load_active(chat)
    if not story:
        return False
    prompt_name = _register_prompt(story, state, st.get_active().get(chat, {}), chat)
    _activate_prompt_for(system, chat, prompt_name)
    return True


