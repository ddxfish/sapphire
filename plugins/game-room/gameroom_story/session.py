def _due_hints(room, turns_in_room):
    """Turn-gated player hints whose gate has passed. Author-typed values are
    coerced, never trusted: a JSON string gate crashed the status route."""
    out = []
    for h in (room.get("player_hints") or []):
        if not isinstance(h, dict):
            continue
        try:
            after = int(h.get("after_turns", 0) or 0)
        except (TypeError, ValueError):
            after = 0
        if turns_in_room >= after:
            out.append(str(h.get("text") or ""))
    return out


def _room_seals(room, state):
    """The current room's sealed blanks, player-facing: what's still open
    (drives the popup), what's filled (the ✍ chip, editable), whether she
    reached for one early (held count → urgency re-raise). Hidden-and-unfound
    objects stay engine-side, same rule as everything else.

    Defensive by design: this runs inside the 12s poll, so ANY throw here
    500s the status route and freezes the whole sidebar — after which
    re-entry paints "No active story" over a story that is running fine
    (finding 3.1). A malformed pack must degrade to a missing chip, never
    to a dead room."""
    out = []
    for name, obj in referee._visible_objects(room, state).items():
        interactions = (obj or {}).get("interactions")
        if not isinstance(interactions, dict):
            continue
        for vname, vspec in interactions.items():
            s = vspec.get("sealed") if isinstance(vspec, dict) else None
            if not isinstance(s, dict):
                continue
            verb = referee._norm(vname)
            key = referee.seal_key(room, name, verb)
            filled = referee.seal_state(state.get("seals"), room, name, verb)
            skipped = state.get("seal_skipped", []) or []
            revealed = state.get("revealed", []) or []
            legacy = referee.legacy_seal_key(name, verb)
            out.append({
                "key": key, "object": name, "verb": verb,
                "ask": s.get("ask") or f"What does the {str(name).replace('_', ' ')} reveal?",
                "has_fallback": bool(s.get("fallback")),
                "filled": filled is not None,
                "text": filled,
                "skipped": key in skipped or legacy in skipped,
                "revealed": key in revealed or legacy in revealed,
                "held": referee.seal_state(state.get("seal_holds"), room, name, verb, 0),
            })
    return out


def fill_seal(system, key, text=None, skip=False, session=None):
    """The player writes (or skips) a sealed blank. Journaled like a dice
    value — at creation time; replay never re-prompts. Re-fill before the
    reveal just appends a newer event (fold takes the last)."""
    chat = _chat_name(system, session)
    story, state = load_active(chat)
    if not story:
        return "No story is active in this chat.", False
    key = str(key or "").strip().lower()
    # Room-scoped resolution: the old scan compared unscoped 'object:verb'
    # across EVERY room and kept the last match, so two rooms sharing an
    # object/verb pair wrote into each other (finding 3.2). Legacy unscoped
    # keys still resolve — first match wins — for saves already holding one.
    spec, legacy_spec = None, None
    for room in story["rooms"].values():
        for name, obj in (room.get("objects") or {}).items():
            # isinstance, not `or {}`: a list-valued interactions is truthy
            # and 500s the fill route (same guard _room_seals carries).
            _ix = (obj or {}).get("interactions")
            for vname, vspec in (_ix.items() if isinstance(_ix, dict) else ()):
                cand = vspec.get("sealed") if isinstance(vspec, dict) else None
                if not isinstance(cand, dict):
                    continue
                if key == referee.seal_key(room, name, vname):
                    spec = cand
                    break
                if legacy_spec is None and key == referee.legacy_seal_key(name, vname):
                    legacy_spec = cand
            if spec is not None:
                break
        if spec is not None:
            break
    spec = spec if spec is not None else legacy_spec
    if not isinstance(spec, dict):
        return f"No sealed blank named '{key}' in this story.", False
    if key in state.get("revealed", []):
        return "That reveal already happened — it's canon now.", False
    slug = story["meta"]["slug"]
    if skip:
        if not spec.get("fallback"):
            return "This blank has no author fallback — the story needs your words here.", False
        # A skip after the blank is already written used to report success
        # and do nothing — the fold takes the player's text, so the author's
        # fallback never fires (finding 3.4). Say what actually happened.
        if state.get("seals", {}).get(key) is not None:
            return ("You've already written this one — clear it from the ✍ chip if you "
                    "want the author's line instead."), False
        st.append(slug, chat, {"event": "seal_skipped", "key": key, "turn": state["turn"]})
        _signal_seals(chat)
        return "Skipped — the author's line will fire instead.", True
    text = str(text or "").strip()
    if not text:
        return "Write something — the blank is the whole point.", False
    st.append(slug, chat, {"event": "sealed", "key": key, "text": text[:2000],
                           "turn": state["turn"]})
    _signal_seals(chat)
    return "Sealed in. She'll find it when she gets there.", True


def _declared_verbs(name, obj, state):
    """Tap-to-draft verb chips for one visible object. Same isinstance guard
    as _room_seals: this runs in the 12s poll, and an author-typed
    `"interactions": 3` used to 500 the status route one line UPSTREAM of
    the 3.1 hardening (post-fix review 2026-08-05)."""
    ix = obj.get("interactions")
