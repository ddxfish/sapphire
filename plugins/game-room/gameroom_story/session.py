def last_played(system, session=None):
    """The chat's most recent FINISHED playthrough (no story active):
    THE END must survive a browser refresh, and the journal is the source of
    truth — replay recovers the final room, flags, and thus the earned
    ending card. (Krem 2026-08-03: 'expected to see the outcome background')."""
    chat = _chat_name(system, session)
    if not chat or st.get_active().get(chat):
        return None
    # Sealed-vault gate (P3-T9): a hidden chat's finished playthrough
    # (ending card, story title) answers like it never happened.
    try:
        if system and system.llm_chat.session_manager.is_chat_hidden(chat):
            return None
    except Exception:
        pass
    best = None
    for slug in rooms.list_stories():
        try:
            meta = st.journal_meta(slug, chat)
            # ISO timestamps compare lexicographically — same clock wrote them
            if meta and (best is None or meta["updated_at"] > best[1]):
                best = (slug, meta["updated_at"])
        except Exception:
            continue
    if not best:
        return None
    slug = best[0]
    try:
        story = rooms.load_story(slug)
        story["rooms"].update(rooms.load_generated_rooms(slug, chat))
        state = st.replay(slug, chat)
        room = story["rooms"].get(state["room"])
        return {
            "story": story["meta"].get("title", slug), "slug": slug,
            "room": room["title"] if room else state["room"],
            "room_id": state["room"], "ended": True,
            "room_backdrop": _backdrop_url(story, room),
            "ending_card": _ending_card_url(story, state, room),
        }
    except Exception as e:
        logger.warning(f"[STORY] last_played('{slug}') failed: {e}")
        return None


