def _end(system, session):
    chat = _chat_name(system, session)
    story, state = load_active(chat)
    # Read, don't pop: active.json is cleared LAST, after the costume and
    # cockpit are actually restored. Popping first meant any throw below left
    # a dirty cockpit and an invisible save whose journal the next ▶Start
    # would archive out from under the player (finding 4.8).
    entry = st.get_active().get(chat)
    if not entry:
        return "No story is active in this chat.", False
    if story and state and not state["ended"]:
        st.append(entry["story"], chat, {"event": "ended", "turn": state["turn"]})
    story_prompt_name = entry.get("prompt_name") or f"story_{entry['story']}"
    from core import prompts
    # Checkbox semantics (Krem's ruling 2026-08-03, post-first-full-play):
    # return_prompt SET → revert to it. NOT set → the ROOM's return prompt
    # (sidebar default, 2026-08-21) if configured, else STAY in the story
    # prompt — the tale leaves a wearable costume behind (dynamic monolith
    # stays registered; user switches prompts whenever they like).
    ret = entry.get("return_prompt") or _room_return_prompt() or None
    if ret:
        st.drop_dynamic(story_prompt_name)
        st.drop_dynamic(f"story_{entry['story']}")   # legacy key, harmless if absent
        _restore_pack()
        prev = ret if ret not in (story_prompt_name, f"story_{entry['story']}") else None
        if prev:
            ok, msg = _activate_prompt_for(system, chat, prev)
            if not ok:
                logger.warning(f"[STORY] restoring prompt '{prev}' failed: {msg}")
                prev = None
        if not prev:
            _activate_prompt_for(system, chat, "default")
        prompt_note = f"prompt restored to '{prev or 'default'}'"
    else:
        st.drop_dynamic(f"story_{entry['story']}") if f"story_{entry['story']}" != story_prompt_name else None
        _restore_pack()                              # keeps story_prompt_name registered
        prompt_note = f"prompt stays '{story_prompt_name}' — switch anytime from the sidebar"
    # Cockpit follows the SAME checkbox ruling as the costume (Krem
    # 2026-08-03, the search_memory-after-end desync): return_prompt set →
    # restore the stashed toolset+extras; not set → the story cockpit STAYS
    # (none + story tools — exactly what the sidebar says). Settings and
    # runtime move together or not at all.
    if ret and "prev_toolset" in entry:
        _stamp_settings(system, chat,
                        {"toolset": entry.get("prev_toolset") or "all",
                         "extra_toolsets": entry.get("prev_extras") or []})
    st.clear_active(chat)
    # v1.3: the journal lives on this chat's rows now — kept until the chat
    # itself is deleted, sealed if the chat is.
    return (f"Story closed. Journal kept with this chat — "
            f"{prompt_note}."), True


