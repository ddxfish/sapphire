# ── Which chat does this call operate on? (findings 1.1 + 1.2) ──────────────
# Two callers, two truths. TOOLS + the ghost hook run inside a turn: their
# chat is core's per-turn effective chat, NOT the global active one — a phone
# call or background conversation must never tick another chat's story.
# ROUTES are a client speaking for a room it already has open: it names its
# session explicitly, because "whatever chat is active right now" is a race
# every second tab, phone turn, and daemon wins.

def _chat_name(system, session=None):
    """The chat this call operates on: an explicit session (the client knows
    its own room) else this turn's effective chat. Never the raw global
    active chat — that's the identity fiction findings 1.1/1.2 named."""
    if session:
        return session
    sm = system.llm_chat.session_manager
    eff = getattr(sm, "_effective_chat_name", None)
    return eff() if callable(eff) else sm.get_active_chat_name()


def _chat_exists(system, chat):
    return system.llm_chat.session_manager.get_settings_for(chat) is not None


def _is_live(system, chat):
    """True when `chat` is the chat this execution context actually runs in —
    the only case where global runtime stamps (system prompt, enabled tools)
    are correct. Otherwise settings are written by name and land when that
    chat next activates (story/reassert asserts them at the door)."""
    sm = system.llm_chat.session_manager
    eff = getattr(sm, "_effective_chat_name", None)
    return chat == (eff() if callable(eff) else sm.get_active_chat_name())


def _settings_for(system, chat):
    """That chat's own settings — never the global active chat's."""
    try:
        return system.llm_chat.session_manager.get_settings_for(chat) or {}
    except Exception as e:
        logger.warning(f"[STORY] settings lookup failed for '{chat}': {e}")
        return {}


def _stamp_settings(system, chat, patch, runtime_toolset=True):
    """Persist chat settings for `chat`; apply the live toolset only when
    that chat is the one running this turn."""
    sm = system.llm_chat.session_manager
    try:
        if _is_live(system, chat):
            sm.update_chat_settings(patch)
        else:
            sm.set_named_chat_settings(chat, patch)
    except Exception as e:
        logger.warning(f"[STORY] settings stamp failed for '{chat}': {e}")
    if not (runtime_toolset and _is_live(system, chat)):
        return
    try:
        system.llm_chat.function_manager.update_enabled_functions(
            [patch.get("toolset") or "all"],
            extra_toolsets=patch.get("extra_toolsets") or None)
    except Exception as e:
        logger.warning(f"[STORY] toolset runtime apply failed: {e}")


def _activate_prompt_for(system, chat, prompt_name):
    """Wear the costume. Live chat → full activation (system prompt + preset
    + settings). Another chat → record the prompt in ITS settings only; the
    live chat keeps wearing whatever it wears."""
    from core import prompts
    if _is_live(system, chat):
        return prompts.activate_prompt(prompt_name, system)
    try:
        ok = system.llm_chat.session_manager.set_named_chat_settings(
            chat, {"prompt": prompt_name})
        return bool(ok), f"Prompt '{prompt_name}' set on '{chat}' (not the live chat)"
    except Exception as e:
        return False, str(e)


def load_active(chat):
    """(story, state) for a chat's active playthrough, or (None, None).
    Generated rooms merge over canonical ones; then the playthrough's user
    layer (placed objects + room-text overrides) and Mad-Libs slot
    substitution — ONE seam, so the referee, the ghost block, full_state,
    and the seal scans all see the same world (plan tmp/open-mansion-plan.md
    keystones K1/K2)."""
    entry = st.get_active().get(chat)
    if not entry:
        return None, None
    try:
        story = rooms.load_story(entry["story"])
    except Exception as e:
        logger.warning(f"[STORY] active story '{entry.get('story')}' failed to load: {e}")
        return None, None
    story["rooms"].update(rooms.load_generated_rooms(entry["story"], chat))
    state = st.replay(entry["story"], chat)
    _merge_user_layer(story, entry["story"], chat, state)
    _apply_slots(story, entry.get("slots") or {})
    return story, state


def _merge_user_layer(story, slug, chat, state):
    """K1 — merge once, at load. User-placed objects join the room dicts.
    Shadow law (2026-08-20, editor v2): a user entry matching a SHIPPED
    name is a deliberate override — `{"_removed": true}` tombstones the
    shipped object; `{"_replace": true, ...}` swaps it wholesale (the
    editor's fidelity-gate lane); anything else field-merges over it (desc/hidden
    replace; interactions overlay per-verb, replacing only `message` so
    shipped mechanics — effects, seals, dice, conditions — survive a
    reword). New names add wholesale, carrying their own per-object
    `condition` (stamped at set-import for non-shipped names), checked by
    the referee's visibility funnel — no gating here. Exits follow the same
    law (shadow + additive, ungated — F2 2026-08-21). Room TEXT overrides
    alone stay zork-gated (meta.open_flag; no flag declared = no line =
    apply always)."""
    try:
        data = st.get_user_layer(slug, chat)
    except Exception as e:
        logger.warning(f"[STORY] user layer read failed for '{slug}': {e}")
        return
    if not data:
        return
    for rid, objs in (data.get("objects") or {}).items():
        try:
            room = story["rooms"].get(int(rid))
        except (TypeError, ValueError):
            room = None
        if not room or not isinstance(objs, dict):
            continue
        target = room.setdefault("objects", {})
        for name, spec in objs.items():
            if not isinstance(spec, dict):
                continue
            if spec.get("_removed"):
                target.pop(name, None)
                continue
            # Fidelity-gate lane (2026-08-21): a _replace entry swaps the
            # shipped object WHOLESALE — machinery included ({} strips it
            # to nothing but what the entry carries). Editor-only marker;
            # the field-merge below stays the law for plain shadows.
            if spec.get("_replace"):
                target[name] = {k: v for k, v in spec.items() if k != "_replace"}
                continue
            if name in target and isinstance(target[name], dict):
                base = dict(target[name])
                if "desc" in spec:
                    base["desc"] = spec["desc"]
                if "hidden" in spec:
                    base["hidden"] = bool(spec["hidden"])
                ints = dict(base.get("interactions") or {})
                for verb, vspec in (spec.get("interactions") or {}).items():
                    if not isinstance(vspec, dict):
                        continue
                    if verb in ints and isinstance(ints[verb], dict):
                        merged = dict(ints[verb])
                        if "message" in vspec:
                            merged["message"] = vspec["message"]
                        ints[verb] = merged
                    else:
                        ints[verb] = vspec
                if ints:
                    base["interactions"] = ints
                target[name] = base
                continue
            target[name] = spec
    # Exits (exits editor, 2026-08-21) — UNGATED like objects (F2, the
    # clown_key law: no implicit zork stamps; authors gate explicitly via
    # visible_when). exit_shadows field-merge over the shipped exit with
    # matching `to` (label/desc/blocked_message replace; shipped mechanics
    # ride UNLESS the shadow carries a `mechanics` unit, which replaces
    # them wholesale — {} strips the door bare); {"_removed": true} walls
    # the door off. add_exits append, dedup by destination, enriched
    # fields (condition/roll/effects/visible_when) verbatim.
    for rid, txt in (data.get("rooms") or {}).items():
        try:
            room = story["rooms"].get(int(rid))
        except (TypeError, ValueError):
            room = None
        if not room or not isinstance(txt, dict):
            continue
        shadows = txt.get("exit_shadows") or {}
        if shadows and room.get("exits"):
            kept = []
            for ex in room["exits"]:
                sh = shadows.get(str(ex.get("to"))) if isinstance(ex, dict) else None
                if not isinstance(sh, dict):
                    kept.append(ex)
                    continue
                if sh.get("_removed"):
                    continue
                merged = dict(ex)
                for f in ("label", "desc", "blocked_message"):
                    if str(sh.get(f) or "").strip():
                        merged[f] = str(sh[f])
                mech = sh.get("mechanics")
                if isinstance(mech, dict):
                    for f in ("condition", "roll", "effects", "visible_when"):
                        merged.pop(f, None)
                        if isinstance(mech.get(f), dict) and mech[f]:
                            merged[f] = mech[f]
                kept.append(merged)
            room["exits"] = kept
        have = {e.get("to") for e in (room.get("exits") or []) if isinstance(e, dict)}
        for ex in (txt.get("add_exits") or []):
            if isinstance(ex, dict) and ex.get("to") not in have:
                room.setdefault("exits", []).append(dict(ex))
                have.add(ex.get("to"))
    # Room TEXT overrides stay zork-gated: pre-open, the shipped tutorial
    # corridor reads as shipped (a different animal from user CONTENT).
    open_flag = (story["meta"].get("open_flag") or "").strip()
    if open_flag and not state["flags"].get(open_flag):
        return
    for rid, txt in (data.get("rooms") or {}).items():
        try:
            room = story["rooms"].get(int(rid))
        except (TypeError, ValueError):
            room = None
        if not room or not isinstance(txt, dict):
            continue
        if str(txt.get("template") or "").strip():
            room["template"] = str(txt["template"])
        if str(txt.get("player_desc") or "").strip():
            room["player_desc"] = str(txt["player_desc"])


def _apply_slots(story, slots):
    """K2 — substitute once, at load: {slot_key} tokens in the story's meta
    text and every string a room dict carries. Values are brace-stripped at
    start, so a slot can't smuggle {ai_name} into core's later template
    pass. Role name/text substitute too — the assembled-setup-as-role pattern
    (_start substitutes before prompt-name derivation, so the costume's
    registered name comes from the RESOLVED role name). Title stays literal."""
    vals = {k: str(v) for k, v in (slots or {}).items() if str(v).strip()}
    if not vals:
        return

    def sub(text):
        for k, v in vals.items():
            text = text.replace("{" + k + "}", v)
        return text

    def walk(node):
        if isinstance(node, str):
            return sub(node) if "{" in node else node
        if isinstance(node, dict):
            return {k: walk(v) for k, v in node.items()}
        if isinstance(node, list):
            return [walk(v) for v in node]
        return node

    meta = story["meta"]
    if isinstance(meta.get("role"), dict):
        r = dict(meta["role"])
        for f in ("name", "text"):
            if r.get(f):
                r[f] = sub(r[f])
        meta["role"] = r
    for f in ("premise", "player_role", "dm_guide"):
        if isinstance(meta.get(f), str) and "{" in meta[f]:
            meta[f] = sub(meta[f])
    for rid in list(story["rooms"]):
        story["rooms"][rid] = walk(story["rooms"][rid])


def _clean_slots(story, slots):
    """Submitted slot values → validated dict. Unknown keys drop; declared-
    but-missing slots take their defaults so no raw {token} ever reaches
    her prompt. Sealed slots ride the seal machinery, never substitution."""
    out = {}
    for decl in rooms.story_slots(story["meta"]):
        if decl["sealed"]:
            continue
        v = str((slots or {}).get(decl["key"], "")).strip() or decl["default"]
        v = v.replace("{", "").replace("}", "")[:1000].strip()
        if v:
            out[decl["key"]] = v
    return out


